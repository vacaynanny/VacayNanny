import { expect, test } from '@playwright/test'

test('destination artwork loads and only configured destinations lead to nanny search', async ({ page }, testInfo) => {
  await page.goto('/')
  const section = page.getByRole('region', { name: 'Good days begin here.' })
  await section.scrollIntoViewIfNeeded()
  await expect(section.getByRole('img')).toHaveCount(4)
  await expect.poll(() => section.getByRole('img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await expect(section.getByRole('link', { name: 'Explore nannies in Diani' })).toHaveAttribute('href', '/nannies?destination=Diani')
  await expect(section.getByRole('link', { name: 'Enquire about care in Watamu' })).toHaveAttribute('href', '/contact?destination=Watamu')
  await section.screenshot({ path: testInfo.outputPath('destinations-desktop.png') })
  await section.getByRole('link', { name: 'Enquire about care in Watamu' }).click()
  await expect(page.getByRole('textbox', { name: 'Subject' })).toHaveValue('Childcare enquiry: Watamu')
  await page.goBack()
  await section.getByRole('link', { name: 'Explore nannies in Diani' }).click()
  await expect(page.getByRole('combobox', { name: 'Destination', exact: true })).toHaveValue('Diani')
  await expect(page.getByRole('status')).toHaveText('1 profile to explore')
})

test('nanny search applies filters, recovers from an empty result and preserves booking dates', async ({ page }, testInfo) => {
  await page.goto('/nannies')
  const filters = page.getByRole('form', { name: 'Find your nanny' })
  await filters.getByRole('searchbox').fill('No matching caregiver')
  await filters.getByRole('button', { name: 'Show my matches' }).click()
  await expect(page.getByRole('status')).toHaveText('0 profiles to explore')
  await expect(page.getByRole('heading', { name: "Let's find another way." })).toBeVisible()
  await filters.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('1 profile to explore')
  await page.screenshot({ path: testInfo.outputPath('nannies-desktop.png'), fullPage: true })
  await filters.getByRole('combobox', { name: 'Destination', exact: true }).selectOption('Diani')
  await filters.getByLabel('Check-in', { exact: true }).fill('2027-06-10')
  await filters.getByLabel('Check-out', { exact: true }).fill('2027-06-12')
  await filters.getByRole('button', { name: 'Show my matches' }).click()
  await expect(page).toHaveURL(/checkOut=2027-06-12/)
  await page.getByRole('button', { name: 'Request care', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Request a nanny' })
  await expect(dialog.getByLabel('Destination', { exact: true })).toHaveValue('Diani')
  await expect(dialog.getByLabel('Check-in Date')).toHaveValue('2027-06-10')
  await expect(dialog.getByLabel('Check-out Date')).toHaveValue('2027-06-12')
})

test('application keeps the image fixed while the desktop form scrolls and changes steps', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/become-a-nanny')
  const panel = page.getByRole('region', { name: 'Nanny application form' })
  const image = page.getByRole('complementary', { name: 'A career built around care' })
  const initialBox = await image.boundingBox()
  await panel.evaluate(element => { element.scrollTop = 650 })
  await expect.poll(() => panel.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  expect(await image.boundingBox()).toEqual(initialBox)
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= window.innerHeight)).toBe(true)
  await panel.getByLabel('First Name').fill('Test')
  await panel.getByLabel('Last Name').fill('Applicant')
  await panel.getByLabel('Date of Birth').fill('1990-01-01')
  await panel.getByLabel('Gender').selectOption('Female')
  await panel.getByLabel('Phone Number').fill('712345678')
  await panel.getByLabel('Email Address').fill('applicant@example.test')
  await panel.getByRole('combobox', { name: /^County/ }).selectOption('Kwale')
  await panel.getByLabel('Town / City').fill('Diani')
  await panel.getByLabel('English', { exact: true }).check()
  await panel.getByRole('button', { name: 'Next: Identity →' }).click()
  await expect(panel.getByRole('heading', { name: 'Identity Verification', exact: true })).toBeVisible()
  await expect.poll(() => panel.evaluate(element => element.scrollTop)).toBe(0)
  await expect(panel.getByRole('heading', { name: 'Identity Verification', exact: true })).toBeFocused()
  expect(await image.boundingBox()).toEqual(initialBox)
  await page.screenshot({ path: testInfo.outputPath('application-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => panel.evaluate(element => getComputedStyle(element).overflowY)).toBe('visible')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await panel.getByRole('combobox', { name: 'Application step' }).selectOption('0')
  await expect(panel.getByRole('heading', { name: 'Personal Information', exact: true })).toBeVisible()
  await expect(panel.getByLabel('First Name')).toHaveValue('Test')
  await page.screenshot({ path: testInfo.outputPath('application-mobile.png'), fullPage: true })
})
